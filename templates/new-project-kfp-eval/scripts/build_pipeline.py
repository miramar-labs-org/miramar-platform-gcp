#!/usr/bin/env python3
"""
Re-generate pipeline.py from notebook.ipynb.

Cells tagged `kfp_step` become component functions; the single cell tagged
`kfp_pipeline` becomes the pipeline() function. Mirrors the Build cell in
notebook.ipynb — run either one.

`# inline: evallib/<module>.py` splice
---------------------------------
Any line in a tagged cell of the exact form

    <indent># inline: evallib/scoring.py

is replaced by the contents of that file, with every line re-indented to
`<indent>`. This lets pure helpers live in `evallib/` (importable + pytest-tested)
while still being embedded verbatim inside a KFP component body — components run
as isolated containers and cannot import repo-local modules.
"""
import argparse
import json
import pathlib
import re

_INLINE_RE = re.compile(r"^(?P<indent>[ \t]*)#\s*inline:\s*(?P<path>\S+)\s*$")


def _splice_inlines(src: str, root: pathlib.Path) -> str:
    out_lines = []
    for line in src.splitlines():
        m = _INLINE_RE.match(line)
        if not m:
            out_lines.append(line)
            continue
        indent = m.group("indent")
        target = (root / m.group("path")).resolve()
        if not target.is_file():
            raise RuntimeError(f"# inline: target not found: {m.group('path')}")
        out_lines.append(f"{indent}# ── inlined from {m.group('path')} ──")
        for body_line in target.read_text().splitlines():
            out_lines.append(f"{indent}{body_line}" if body_line.strip() else "")
    return "\n".join(out_lines)


def build_pipeline(notebook_path="notebook.ipynb"):
    root = pathlib.Path(notebook_path).resolve().parent
    nb = json.loads(pathlib.Path(notebook_path).read_text())

    step_srcs, pipeline_src = [], None
    for cell in nb["cells"]:
        if cell["cell_type"] != "code":
            continue
        tags = cell.get("metadata", {}).get("tags", [])
        src = "".join(cell["source"])

        if "kfp_step" in tags:
            step_srcs.append(_splice_inlines(src, root))
        elif "kfp_pipeline" in tags:
            pipeline_src = _splice_inlines(src, root)

    if not step_srcs:
        raise RuntimeError("No cells tagged 'kfp_step' found.")
    if pipeline_src is None:
        raise RuntimeError("No cell tagged 'kfp_pipeline' found.")

    names = [
        m.group(1)
        for s in step_srcs
        for m in [re.search(r"^def (\w+)\(", s, re.MULTILINE)]
        if m
    ]

    out  = "# Generated by notebook.ipynb — do not edit manually.\n"
    out += "# Re-run the Build cell (or scripts/build_pipeline.py) to regenerate.\n\n"
    out += "from typing import NamedTuple\n"
    out += "from kfp import dsl\n"
    out += "from kfp.dsl import Input, Output, Artifact\n\n\n"
    out += "\n\n\n".join(step_srcs)
    out += "\n\n\n"
    out += pipeline_src
    out += "\n"
    (root / "pipeline.py").write_text(out)
    print(f"Wrote pipeline.py — {len(names)} component(s): {', '.join(names)}")


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--notebook", default="notebook.ipynb")
    args = parser.parse_args()
    build_pipeline(args.notebook)
